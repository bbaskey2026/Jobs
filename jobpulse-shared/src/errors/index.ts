export enum ErrorCode {
  // General Errors
  INTERNAL_SERVER_ERROR = 'INTERNAL_SERVER_ERROR',
  VALIDATION_ERROR = 'VALIDATION_ERROR',
  BAD_REQUEST = 'BAD_REQUEST',
  NOT_FOUND = 'NOT_FOUND',
  CONFLICT = 'CONFLICT',
  RATE_LIMIT_EXCEEDED = 'RATE_LIMIT_EXCEEDED',

  // Authentication & Authorization
  UNAUTHORIZED = 'UNAUTHORIZED',
  FORBIDDEN = 'FORBIDDEN',
  INVALID_CREDENTIALS = 'INVALID_CREDENTIALS',
  TOKEN_EXPIRED = 'TOKEN_EXPIRED',
  TOKEN_INVALID = 'TOKEN_INVALID',
  ACCOUNT_LOCKED = 'ACCOUNT_LOCKED',
  EMAIL_ALREADY_EXISTS = 'EMAIL_ALREADY_EXISTS',
  EMAIL_NOT_VERIFIED = 'EMAIL_NOT_VERIFIED',
  CSRF_TOKEN_INVALID = 'CSRF_TOKEN_INVALID',

  // Job Domain Errors
  JOB_NOT_FOUND = 'JOB_NOT_FOUND',
  JOB_EXPIRED = 'JOB_EXPIRED',
  JOB_ALREADY_CLOSED = 'JOB_ALREADY_CLOSED',
  JOB_DUPLICATE_DETECTED = 'JOB_DUPLICATE_DETECTED',
  INVALID_JOB_STATUS_TRANSITION = 'INVALID_JOB_STATUS_TRANSITION',

  // Alert & Bookmark Errors
  ALERT_LIMIT_EXCEEDED = 'ALERT_LIMIT_EXCEEDED',
  BOOKMARK_ALREADY_EXISTS = 'BOOKMARK_ALREADY_EXISTS',

  // File & Upload Errors
  FILE_TOO_LARGE = 'FILE_TOO_LARGE',
  UNSUPPORTED_FILE_TYPE = 'UNSUPPORTED_FILE_TYPE',
  MALICIOUS_FILE_DETECTED = 'MALICIOUS_FILE_DETECTED',

  // Provider / Integration Errors
  PROVIDER_UNAVAILABLE = 'PROVIDER_UNAVAILABLE',
  PROVIDER_RATE_LIMITED = 'PROVIDER_RATE_LIMITED',
  PROVIDER_RESPONSE_INVALID = 'PROVIDER_RESPONSE_INVALID'
}

export interface ApiErrorDetail {
  field?: string;
  message: string;
  code?: string;
}

export interface ApiErrorResponse {
  success: false;
  statusCode: number;
  errorCode: ErrorCode | string;
  message: string;
  errors?: ApiErrorDetail[];
  requestId?: string;
  timestamp: string;
}
